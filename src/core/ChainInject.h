#pragma once

// **让"启动壳拉起真身"这条路也能挂起注入。**
//
// 起因是一次真实的失败：同一个游戏、同一个启动方式，一次注入时进程里有 98 个模块
// （旁听接上了 5 个钩子，功能正常），下一次 125 个模块（**一个钩子都没接上**，
// 工具表现为"完全没效果"，而日志里除了模块数之外几乎一样）。
//
// 根因不在旁听，在注入时机：这个游戏（和大多数 Steam 游戏一样）第一个进程只是个
// 活几百毫秒的**启动壳**，真身是壳拉起来的。UI 只能对**自己创建**的进程做挂起注入
// （主线程一条指令都没跑，稳赢），而真身不是它创建的 —— 只能退回"发现进程再注入"，
// 那时游戏可能已经把 Streamline / NGX 的函数指针取走了。**是竞态，赢不赢看运气。**
//
// 做法：核心被注进壳里之后，在壳里挂上 CreateProcess 的钩子。壳拉起真身时：
//   1. 强行加上 CREATE_SUSPENDED（不管调用方有没有传）
//   2. 往子进程里注入同一个 core DLL
//   3. 等它报告"钩子装好了"
//   4. 调用方没要求挂起的话，再 ResumeThread
// 子进程里的 core 会同样挂上这个钩子，所以多层壳自动递归解决。
//
// 边界：
//   · 只在**还没接管图形**的进程里挂（壳不渲染）。已经拿到 D3D12 设备说明我们就是
//     真身，那时候游戏拉起的子进程（崩溃上报器之类）不该被注入。
//   · 位数不同的子进程直接放过 —— 往 32 位进程里塞 64 位 DLL 只会让它起不来。
//   · 按子进程实际映像文件名排除专用崩溃上报器，不向这些诊断进程注入图形核心。
//   · 链式注入有次数上限，防止病态情况下无限展开。
//   · **任何一步失败都必须让子进程正常跑起来**。宁可少一个功能，
//     也不能把玩家的游戏卡死在启动瞬间。

#include <windows.h>

namespace DXL {

// selfModule = core 自己的模块句柄（用来拿 DLL 路径，注入子进程要用同一个文件）。
// canTakeOver 为 false 时不挂钩子（比如已经确定本进程就是渲染进程）。
void InstallChainInject(HMODULE selfModule) noexcept;

// 本进程已经接管图形了 —— 之后不再对子进程做链式注入。
void ChainInjectStopAfterGraphics() noexcept;

// 挂上了几个钩子（0 = 没挂上，壳里就该怀疑它是不是走 CreateProcess 拉起真身的）
unsigned int ChainInjectHooks() noexcept;
// 链式注入成功了几次
unsigned int ChainInjectCount() noexcept;

}  // namespace DXL
